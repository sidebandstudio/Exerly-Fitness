        capture(app, "reminder-device-scheduled")
        // Scheduling, permission, cancellation and saved intent run everywhere.
        // A busy hosted simulator can miss the wall-clock delivery window before
        // it reaches Home. Keep actual banner delivery as an explicit device run.
        if ProcessInfo.processInfo.environment["EXERLY_NOTIFICATION_DELIVERY"] == "1" {
            XCUIDevice.shared.press(.home)
            XCTAssertTrue(springboard.staticTexts["Sleep reminder"].firstMatch.waitForExistence(timeout: 150), springboard.debugDescription)
            capture(springboard, "reminder-delivered-by-ios")
            app.activate()
        }
        let retained = try await request("GET", "/api/preferences", token: token)
        let values = try XCTUnwrap(retained["values"] as? [String: Any])
        XCTAssertEqual((values["reminders"] as? [String: Bool])?["sleep"], true)
        XCTAssertEqual((values["reminderTimes"] as? [String: String])?["sleep"], dueTime)
        tap(app.switches["reminders.device"], in: app)
        XCTAssertTrue(app.descendants(matching: .any)["reminders.scheduled.none"].waitForExistence(timeout: 10))
        capture(app, "reminder-device-disabled")
        app.terminate(); app.launchArguments = []; app.launch()
        XCTAssertTrue(todayScreen(app).waitForExistence(timeout: 15))
        openReminders(app)
        XCTAssertEqual(app.switches["reminders.sleep"].value as? String, "1")
        reveal(app.switches["reminders.device"], in: app)
        XCTAssertEqual(app.switches["reminders.device"].value as? String, "0")
    }

    private func openReminders(_ app: XCUIApplication) {
        tap(app.buttons["Profile"], in: app)
        tap(app.buttons["profile.reminders"], in: app)
        XCTAssertTrue(app.navigationBars["Reminders"].waitForExistence(timeout: 10))
        XCTAssertTrue(app.switches["reminders.sleep"].waitForExistence(timeout: 15))
    }

    private func openPreferences(_ app: XCUIApplication) {
        tap(app.buttons["Profile"], in: app)
        tap(app.buttons["profile.preferences"], in: app)
        XCTAssertTrue(app.navigationBars["Your details"].waitForExistence(timeout: 10))
        XCTAssertTrue(app.textFields["preferences.name"].waitForExistence(timeout: 15))
        let ready = NSPredicate(format: "enabled == true")
        expectation(for: ready, evaluatedWith: app.buttons["Refresh preferences"])
        waitForExpectations(timeout: 15)
    }

    private func selectProgress(_ title: String, in app: XCUIApplication) {
        if app.buttons["progress.section"].exists { tap(app.buttons["progress.section"], in: app) }
        tap(app.buttons[title], in: app)
    }
    /// Taps a photo in iOS 26's photo picker. Its privacy introduction can
    /// arrive after the grid, and the remote grid can report a visible
    /// thumbnail as not hittable, so tap its visible center.
    private func choosePickerPhoto(_ photo: XCUIElement, in app: XCUIApplication) {
        XCTAssertTrue(photo.waitForExistence(timeout: 10))
        dismissPhotoPickerIntroduction(in: app)
        if photo.isHittable { photo.tap() } else {
            XCTAssertTrue(app.frame.contains(CGPoint(x: photo.frame.midX, y: photo.frame.midY)), "The photo is outside the visible picker")
            photo.coordinate(withNormalizedOffset: CGVector(dx: 0.5, dy: 0.5)).tap()
        }
    }
    private func dismissPhotoPickerIntroduction(in app: XCUIApplication) {
        let introduction = app.otherElements["PXGSingleViewContainerView_AX"]
        if introduction.exists, introduction.label.hasPrefix("Private Access to Photos") {
            let close = introduction.buttons["Close"]
            if close.exists { close.tap() }
        }
    }
